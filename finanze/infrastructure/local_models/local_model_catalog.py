MB = 1_000_000


def _entry(
    repo: str,
    quant: str,
    name: str,
    size: int,
    ram: int,
    params: str,
    license: str,
    decisions: bool = False,
    languages: list[str] | None = None,
    vision_size: int | None = None,
    vision_ram: int | None = None,
) -> LocalModelCatalogEntry:
    return LocalModelCatalogEntry(
        id=f"{repo}:{quant}",
        name=name,
        repo=repo,
        quant=quant,
        size=size,
        ram=ram,
        params=params,
        license=license,
        decisions=decisions,
        languages=languages,
        vision_size=vision_size,
        vision_ram=vision_ram,
    )


